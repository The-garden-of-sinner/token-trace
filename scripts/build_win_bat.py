#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build one self-contained Windows .bat for token-trace.

The batch file carries the full source of every runtime module (trace_server.py,
gen_trace.py, pricing.py and the sources/ package) plus the application icon as
a zlib-compressed, base64-encoded blob. Double-clicking it needs no other project
file: a tiny pure-ASCII loader is extracted into %LOCALAPPDATA%\\TokenTrace, which
installs an in-memory import hook (MetaPathFinder) so absolute and relative
imports all resolve from the bundle, then execs the server. "shortcut" writes the
embedded icon and creates Desktop + Start Menu shortcuts that point back at this
very .bat.

The import hook matters since v1.3.0: gen_trace imports sources.bridge and both
server modules import pricing. Bundling only the two historical files would make
the .bat die with ImportError before the first request.

    python3 scripts/build_win_bat.py
    -> dist/TokenTrace.bat          (the single Release asset)

Design constraints (see README):
  * The .bat is pure ASCII with CRLF endings -- no codepage/BOM issues on
    Chinese Windows, and no non-ASCII path is baked into the file.
  * Only launcher.py (ASCII) and TokenTrace.ico (binary) are written to disk,
    and the icon is only written by the explicit "shortcut" command.
  * Python discovery copies the proven pattern from workbuddy-token-monitor.

Note on signing: a .bat is a text script; Windows Authenticode does not apply to
it. Integrity is covered by dist/SHA256SUMS, and windows/sign-release.ps1 is an
optional entry point for signing the PowerShell sources with your own certificate.
"""

import base64
import json
import os
import subprocess
import sys
import zlib

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(BASE, "dist")
OUT = os.path.join(DIST, "TokenTrace.bat")
ICON = os.path.join(BASE, "assets", "TokenTrace.ico")
VERSION_FILE = os.path.join(BASE, "scripts", "VERSION")
# 相对仓库根的路径；key 同时作为 bundle 里的模块键，loader 按
# fullname.replace(".", "/") 查 "xxx.py" / "xxx/__init__.py"。
SOURCES = ("trace_server.py", "gen_trace.py", "pricing.py",
           "sources/__init__.py", "sources/bridge.py",
           "sources/codex.py", "sources/zcode.py", "sources/dsh.py",
           "sources/_zstd.py")

BAT_HEAD = r"""@echo off
rem Token Trace @VERSION@ - single-file Windows launcher. No other project files needed.
rem Generated by scripts/build_win_bat.py -- do not edit by hand.
setlocal EnableExtensions
if not defined LOCALAPPDATA set "LOCALAPPDATA=%USERPROFILE%\AppData\Local"
set "APPDIR=%LOCALAPPDATA%\TokenTrace"
set "VER=@VERSION@"
set "PORT=%TRACE_PORT%"
if not defined PORT set "PORT=8765"
if not exist "%APPDIR%" mkdir "%APPDIR%" 2>nul

set "PYEXE="
set "PYARGS="
if defined TRACE_PYTHON call :probe "%TRACE_PYTHON%" && goto found
call :probe py -3 && goto found
call :probe python && goto found
call :probe python3 && goto found
for /d %%D in ("%LOCALAPPDATA%\Programs\Python\Python3*") do call :probe "%%~D\python.exe" && goto found
for /d %%D in ("%ProgramFiles%\Python3*") do call :probe "%%~D\python.exe" && goto found
for /d %%D in ("C:\Python3*") do call :probe "%%~D\python.exe" && goto found
for %%D in ("%USERPROFILE%\anaconda3" "%USERPROFILE%\miniconda3") do call :probe "%%~D\python.exe" && goto found
for /d %%D in ("%USERPROFILE%\.workbuddy\binaries\python\versions\*") do call :probe "%%~D\python.exe" && goto found
echo Python 3.8+ not found.
echo Install from python.org (tick "Add python.exe to PATH"), or set TRACE_PYTHON=C:\path\to\python.exe
pause
exit /b 1

:found
set "URL=http://127.0.0.1:%PORT%"
if /i "%~1"=="version" goto version
if /i "%~1"=="help" goto help
if /i "%~1"=="shortcut" goto shortcut
if /i "%~1"=="stop" goto stop
if /i "%~1"=="status" goto status

echo(
echo   Token Trace v%VER%  -  local token trajectory viewer
echo   ---------------------------------------------------------
echo(

rem Already running? Just open the browser, never start a second process.
%PYEXE% %PYARGS% -c "import urllib.request,sys;sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:%PORT%/health',timeout=1).read().strip()==b'ok' else 1)" >nul 2>&1
if not errorlevel 1 goto open

call :extract
if errorlevel 1 exit /b 1

start "Token Trace" /MIN %PYEXE% %PYARGS% "%APPDIR%\launcher.py" --port %PORT%
set /a TRIES=0
:wait
%PYEXE% %PYARGS% -c "import urllib.request,sys;sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:%PORT%/health',timeout=1).read().strip()==b'ok' else 1)" >nul 2>&1
if not errorlevel 1 goto open
set /a TRIES+=1
if %TRIES% GEQ 20 goto failwait
ping -n 2 127.0.0.1 >nul
goto wait

:failwait
echo Service did not become ready on port %PORT%. Try "status" or check the minimized window.
exit /b 1

:open
start "" "%URL%/"
echo   Ready: %URL%/
exit /b 0

:stop
%PYEXE% %PYARGS% -c "import urllib.request;urllib.request.urlopen(urllib.request.Request('http://127.0.0.1:%PORT%/shutdown',data=b'',method='POST'),timeout=3).read()" >nul 2>&1
if errorlevel 1 (echo Not running on port %PORT%.) else (echo Stopped.)
exit /b 0

:status
%PYEXE% %PYARGS% -c "import urllib.request;print(urllib.request.urlopen('http://127.0.0.1:%PORT%/api/health',timeout=2).read().decode())"
if errorlevel 1 echo Not running on port %PORT%.
exit /b 0

:version
echo Token Trace %VER%
exit /b 0

:help
echo Token Trace %VER% - single-file launcher, no install needed.
echo(
echo Usage: TokenTrace.bat [command]
echo(
echo   (no arg)   Start the service and open the browser
echo   stop       Stop the service on the current port
echo   status     Print /api/health as JSON
echo   shortcut   Create Desktop + Start Menu shortcuts with the app icon
echo   version    Print the version
echo   help       Show this help
echo(
echo Environment:
echo   TRACE_PORT=9000                    change port (default 8765)
echo   TRACE_PYTHON=C:\path\python.exe   pick a Python 3.8+ interpreter
echo(
echo Home: https://github.com/The-garden-of-sinner/token-trace
exit /b 0

:shortcut
call :extract
if errorlevel 1 exit /b 1
%PYEXE% %PYARGS% "%APPDIR%\launcher.py" --write-icon
if errorlevel 1 (echo Failed to write the application icon.& exit /b 1)
powershell -NoProfile -ExecutionPolicy Bypass -Command "& {$w=New-Object -ComObject WScript.Shell; $dirs=@([Environment]::GetFolderPath('Desktop'),[Environment]::GetFolderPath('Programs')); foreach($d in $dirs){if(-not(Test-Path -LiteralPath $d)){[void](New-Item -ItemType Directory -Path $d -Force)}; $s=$w.CreateShortcut((Join-Path $d 'Token Trace.lnk')); $s.TargetPath='%~f0'; $s.WorkingDirectory='%~dp0'; $s.IconLocation='%APPDIR%\TokenTrace.ico,0'; $s.Description='Token Trace - local token trajectory viewer'; $s.Save()}; Write-Host 'Shortcuts created: Desktop + Start Menu.'}"
if errorlevel 1 (echo Failed to create shortcuts.& exit /b 1)
exit /b 0

:extract
rem Rewrite every time: a newer TokenTrace.bat may carry a newer payload.
%PYEXE% %PYARGS% -c "import sys;L=open(sys.argv[1]).read().splitlines();i=L.index('__PY_BUNDLE__');j=L.index('__PY_END__');open(sys.argv[2],'w').write('\n'.join(L[i+1:j]))" "%~f0" "%APPDIR%\launcher.py"
if errorlevel 1 (echo Failed to unpack the bundled server.& exit /b 1)
exit /b 0

:probe
rem Version gate: exit 0 only for Python >= 3.8. Avoids cmd metacharacters.
%1 %~2 -c "import sys;sys.exit(max(0,min(1,38-sys.version_info[0]*10-sys.version_info[1])))" >nul 2>&1
if errorlevel 1 exit /b 1
set "PYEXE=%1"
set "PYARGS=%~2"
exit /b 0

__PY_BUNDLE__
"""

BAT_TAIL = "__PY_END__\n"

LOADER_HEAD = """import base64, json, os, sys, zlib
import importlib.abc, importlib.util
_S = \"\"\"
"""

LOADER_TAIL = """\"\"\"
_D = os.path.dirname(os.path.abspath(__file__))
_M = json.loads(zlib.decompress(base64.b64decode(_S)).decode("utf-8"))
if len(sys.argv) > 1 and sys.argv[1] == "--write-icon":
    with open(os.path.join(_D, "TokenTrace.ico"), "wb") as _f:
        _f.write(base64.b64decode(_M["icon.ico"]))
    raise SystemExit(0)
_PY = dict((k, v) for k, v in _M.items() if k.endswith(".py"))

class _MemLoader(importlib.abc.Loader):
    def __init__(self, name, src, is_pkg):
        self.name, self.src, self.is_pkg = name, src, is_pkg
    def create_module(self, spec):
        return None
    def exec_module(self, mod):
        rel = self.name.replace(".", "/") + ("/__init__.py" if self.is_pkg else ".py")
        mod.__file__ = os.path.join(_D, rel)
        if self.is_pkg:
            mod.__path__ = [os.path.join(_D, *self.name.split("."))]
        exec(compile(self.src, mod.__file__, "exec"), mod.__dict__)

class _MemFinder(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        rel = fullname.replace(".", "/")
        for key, is_pkg in ((rel + "/__init__.py", True), (rel + ".py", False)):
            if key in _PY:
                return importlib.util.spec_from_loader(
                    fullname, _MemLoader(fullname, _PY[key], is_pkg),
                    is_package=is_pkg)
        return None

sys.meta_path.insert(0, _MemFinder())
_D2 = {"__name__": "__main__", "__file__": os.path.join(_D, "trace_server.py"),
       "__builtins__": __builtins__, "__package__": None, "__doc__": None}
exec(compile(_PY["trace_server.py"], _D2["__file__"], "exec"), _D2)
"""


def main():
    if not os.path.isfile(ICON):
        print("icon missing, generating it first ...")
        subprocess.check_call([sys.executable, "-B",
                               os.path.join(BASE, "scripts", "make_icon.py")])
    with open(VERSION_FILE, "r", encoding="utf-8") as f:
        ver = f.read().strip()

    mods = {}
    for name in SOURCES:
        with open(os.path.join(BASE, name), "r", encoding="utf-8") as f:
            mods[name] = f.read()
    with open(ICON, "rb") as f:
        mods["icon.ico"] = base64.b64encode(f.read()).decode("ascii")

    raw = json.dumps(mods, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    packed = base64.b64encode(zlib.compress(raw, 9)).decode("ascii")
    chunks = [packed[i:i + 120] for i in range(0, len(packed), 120)]

    head = BAT_HEAD.replace("@VERSION@", ver)
    text = (head + LOADER_HEAD + "\n".join(chunks) + "\n"
            + LOADER_TAIL + BAT_TAIL)
    data = text.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii")
    data.decode("ascii")  # hard guarantee: no non-ASCII byte in the .bat

    if not os.path.isdir(DIST):
        os.makedirs(DIST)
    with open(OUT, "wb") as f:
        f.write(data)

    print("version   : %s" % ver)
    print("embedded  : %s + icon.ico (%d bytes)" %
          (", ".join(SOURCES), os.path.getsize(ICON)))
    print("source    : %d bytes -> zlib %d -> base64 %d"
          % (len(raw), len(zlib.compress(raw, 9)), len(packed)))
    print("TokenTrace: %d bytes / %d lines / CRLF / pure ASCII"
          % (len(data), data.count(b"\r\n")))
    print("output    : %s" % OUT)


if __name__ == "__main__":
    main()
